"""Writes entry.py: the @nki.jit entry points of decode_step.step_body, with one explicit argument per per-layer
tensor (a kernel takes tensors, not lists of tensors; separate arguments keep every tensor zero-copy).
Argument names are f"{group}_{i}", i = index among the layers of that kind. Run: python gen_entry.py"""
import os

SHARED = "x_rows, cosb, sinb, bt, slot, pos, pages, ident_in, mk_in, bmask_in"
LG = ("ln1", "ln2", "Wr", "Wsgu", "Wsd", "Wsg", "gu", "dn")       # every layer
GG = ("Win", "Wout", "cw", "alog", "dtb", "nw", "sa", "sb")        # DeltaNet layers
AG = ("Wqkv", "Wo", "qnw", "knw", "kc", "vc")                      # attention layers


def groups(pat):
    n = {"L": len(pat), "G": pat.count("G"), "A": pat.count("A")}
    out = {}
    for k, gs in (("L", LG), ("G", GG), ("A", AG)):
        for g in gs:
            out[g] = [f"{g}_{i}" for i in range(n[k])]
    return out


def entry(fname, pat, lm):
    gr = groups(pat)
    allh = ",\n        ".join(", ".join(v) for v in gr.values())
    d = "dict(" + ", ".join(f"{g}=(" + ", ".join(v) + ",)" for g, v in gr.items()) + ")"
    lmk = ", lnf=None, lmw=None, vocab=0" if lm else ""
    lmc = ", lm=(lnf, lmw, vocab)" if lm else ""
    return f'''

@nki.jit
def {fname}({SHARED},
        {allh},
        gmap=(), pattern={pat!r}, ranks=None{lmk}):
    return step_body({SHARED}, {d}, gmap, pattern=pattern, ranks=ranks{lmc})
'''


if __name__ == "__main__":
    src = ('# SPDX-License-Identifier: Apache-2.0\n'
           '"""Generated by gen_entry.py; do not edit. Entry points of decode_step.step_body."""\n'
           'import nki\n\nfrom .decode_step import step_body\n')
    src += entry("decode_step", "GGGA" * 10, lm=False) + entry("decode_step_lm", "GGGA" * 10, lm=True)
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "entry.py"), "w").write(src)
    print("ok", len(src))
