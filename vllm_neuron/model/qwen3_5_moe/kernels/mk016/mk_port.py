"""40-layer decode step in the vLLM-Neuron 0.29 port's tensor layouts (one TP=4 rank, LNC=2, S=1).

Differences from mk_step (M4a contract):
  * heavy per-layer tensors are passed as separate kernel arguments (zero-copy, the port's own parameters and
    buffers): routed experts gu[l] [E, H, 256] / dn[l] [E, 128, H] (40 each), GDN state cs[g] / rs[g] (30 each),
    paged KV k[a] / v[a] [NBLK, 1, 256, 256] (10 each, vLLM's per-layer caches);
  * GDN state is slot-indexed and updated in place: rs[g] [slots, ckpt, Hv, Dk, Dv] fp32 (port layout),
    cs[g] [slots, ckpt, NC*128*3*CT] fp32 (MK-native conv layout, kept by the port when QWEN35_DECODE_MK=1);
    rows ridx[b] (read) / widx[b] (write) = slot * n_ckpt + ckpt;
  * the state and KV inputs are returned unchanged as outputs -> wrap_nki input/output aliases.
Per-layer weights in MK layout: Win (tt012 per-pcore in_proj, flat), cw (tt012 conv, flat fp32), Wout [1024, H],
alog/dtb [8] fp32, nw [128] fp32; Wqkv [H, 2560], Wo [1024, H], qnw/knw [256] fp32; ln1/ln2 [H] fp32;
Wr [H, 256] fp32, Wsgu [H, 256], Wsd [128, H], Wsg [H, 1].
Every per-layer tensor is its own kernel argument (zero-copy; entry generated by gen_mk_port.py).
"""
import os

import nki.isa as nisa
import nki.language as nl

from .gdn_block import contig_io_tiles, dims, gdn_mixer, gdn_win_load, slot_io_tiles, load_mk
from .mk_common import BF, F32, H, KT, mk_fold, mul_w_rows, rs_cols, w_cols, reduce_residual, rmsnorm_rows, row_rstd, rows_to_std, sb, store_rows
from .mk_gqa import gqa_mixer
from .mk_lmhead import lm_head_tail, lm_tile_load
from .moe_block import TOPK, dedup_bufs, dedup_on, moe_block

PATTERN = "GGGA" * 10


def port_body(x_rows, cosb, sinb, bt, slot, pos, ridx, widx, ident_in, mk_in, bmask_in, W, pattern=PATTERN,
              ranks=None, lm=None):
    """W: dict group -> tuple of per-layer tensors (gen_mk_port.LG / GG / AG). Returns (h_out, *cs, *rs, *kc, *vc);
    the state / KV outputs ARE the inputs (in-place writes; wrap_nki aliases them)."""
    NC = nl.num_programs(0)
    pid = nl.program_id(0) if NC > 1 else 0
    B = x_rows.shape[0]
    HV_C = dims(NC, B)[1]
    HW = H // NC
    h_out = nl.ndarray((B, H), dtype=BF, buffer=nl.shared_hbm)

    ident = sb((128, 128), BF)
    nisa.dma_copy(dst=ident, src=ident_in)
    ones = sb((128, 128), BF)
    nisa.memset(ones, 1.0)
    ones_f = sb((B, 128))
    nisa.memset(ones_f, 1.0)
    J = HV_C * B
    mk = load_mk(mk_in)
    bmask = sb((B, TOPK * B))
    nisa.dma_copy(dst=bmask, src=bmask_in)
    hR = sb((B, H), BF)
    nisa.dma_copy(dst=hR, src=x_rows)
    # ridx fp32 = per-row active mask -> contiguous state path (kernel row b = pool row b, n_ckpt 1)
    sio = contig_io_tiles(ridx, B) if 'float32' in str(ridx.dtype) else slot_io_tiles(ridx, widx, B, NC, pid)

    ig = ia = 0
    # the dedup expert ring is zeroed once per megakernel, not per layer
    # HW: hoisting the ring across layers hangs the B=32 decode step (NRT_TIMEOUT): the
    # cross-layer reuse of the same SBUF buffers inside a runtime (fori) tail loop is not safe. Default off.
    ebuf = dedup_bufs(W["gu"][0], W["dn"][0]) if (dedup_on(B) and os.environ.get("MK_EBUF_ONCE", "0") == "1") else None
    wnext = ()
    LMPF = int(os.environ.get("MK_LMPF", "0"))  # first LMPF lm_head tiles before the last MoE AR
    lm_pre = ()
    PFG = int(os.environ.get("MK_PFG", "0"))  # next GDN layer's first PFG in_proj k-groups early
    for l, kind in enumerate(pattern):
        FOLD = mk_fold()
        rsc1 = row_rstd(hR, B) if FOLD else None
        rk1 = rs_cols(rsc1, ident, B) if FOLD == 4 else None
        x1 = rmsnorm_rows(hR, W["ln1"][l], B) if not FOLD else (mul_w_rows(hR, W["ln1"][l], B) if FOLD == 2 else hR)
        xT = rows_to_std(x1, KT, ident, B, wcol=w_cols(W["ln1"][l], B) if FOLD in (3, 4) else None, rk=rk1)
        rsc1 = None if FOLD == 4 else rsc1
        if kind == "G":
            gsc = nl.ndarray((NC * B * 2 * HV_C,), dtype=BF, buffer=nl.shared_hbm)
            cs, rs = W["cs"][ig], W["rs"][ig]
            y = gdn_mixer(xT, W["Win"][ig], W["Wout"][ig], W["cw"][ig], cs, rs, W["alog"][ig], W["dtb"][ig],
                          W["nw"][ig], ident, ones, mk, cs, rs, None, gsc, B, NC, pid, sio=sio, rsc=rsc1,
                          w_pre=wnext)
            wnext = ()
            ig += 1
        else:
            qs = nl.ndarray((NC * B, 1536), dtype=BF, buffer=nl.shared_hbm)
            y = gqa_mixer(xT, W["Wqkv"][ia], W["Wo"][ia], W["qnw"][ia], W["knw"][ia], cosb, sinb, W["kc"][ia],
                          W["vc"][ia], bt, slot, pos, ident, qs, B, NC, pid, blk_off=0, rsc=rsc1)
            ia += 1
        hR = reduce_residual(y, hR, B, NC, pid, ranks, f"x{l}")
        x2 = rmsnorm_rows(hR, W["ln2"][l], B) if not FOLD else (mul_w_rows(hR, W["ln2"][l], B) if FOLD == 2 else hR)
        fold = (row_rstd(hR, B), None if FOLD == 2 else W["ln2"][l]) if FOLD else None
        rk2 = rs_cols(fold[0], ident, B) if FOLD == 4 else None
        fold = None if FOLD == 4 else fold
        ym = moe_block(x2, W["Wr"][l], W["gu"][l], W["dn"][l], W["Wsgu"][l], W["Wsd"][l], W["Wsg"][l], ident,
                       ones_f, bmask, B, NC, pid, fold=fold,
                       wcol=w_cols(W["ln2"][l], B, pmaj=True) if FOLD in (3, 4) else None, rk=rk2, ebuf=ebuf)
        ymb = sb((B, HW), BF)
        nisa.tensor_copy(dst=ymb, src=ym)
        if PFG and l + 1 < len(pattern) and pattern[l + 1] == "G":
            wnext = tuple(gdn_win_load(W["Win"][ig], g, NC, pid, B) for g in range(PFG))
        if lm is not None and LMPF and l == len(pattern) - 1:
            lm_pre = tuple(lm_tile_load(lm[1], t, pid) for t in range(LMPF))
        hR = reduce_residual(ymb, hR, B, NC, pid, ranks, f"m{l}")

    if lm is not None:  # final norm + vocab-parallel lm_head in-kernel; h_out = normed hidden
        logits = nl.ndarray((B, lm[2]), dtype=BF, buffer=nl.shared_hbm)
        lm_head_tail(hR, lm[0], lm[1], logits, h_out, ident, B, NC, pid, lm[2], w_pre=lm_pre)
        return (h_out, logits) + tuple(W["cs"]) + tuple(W["rs"]) + tuple(W["kc"]) + tuple(W["vc"])
    store_rows(h_out, hR, NC, pid)
    return (h_out,) + tuple(W["cs"]) + tuple(W["rs"]) + tuple(W["kc"]) + tuple(W["vc"])
